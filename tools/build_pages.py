def build_sitemap():
    urls = [(BASE, '1.0', 'weekly', True), (BASE + 'en/', '0.8', 'monthly', False)]
    urls += [(f"{BASE}{p['slug']}/", '0.9' if p['slug'] in ('quran', 'prayer-times', 'azkar', 'install') else '0.7', 'monthly', False) for p in PAGES]
    urls.append((BASE + 'privacy.html', '0.3', 'yearly', False))
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml" xmlns:video="http://www.google.com/schemas/sitemap-video/1.1">']
    for loc, pr, cf, video in urls:
        out.append('  <url>')
        out.append(f'    <loc>{loc}</loc>\n    <lastmod>{DATE}</lastmod>\n    <changefreq>{cf}</changefreq>\n    <priority>{pr}</priority>')
        if loc in (BASE, BASE + 'en/'):
            out.append(f'    <xhtml:link rel="alternate" hreflang="ar" href="{BASE}"/>')
            out.append(f'    <xhtml:link rel="alternate" hreflang="en" href="{BASE}en/"/>')
            out.append(f'    <xhtml:link rel="alternate" hreflang="x-default" href="{BASE}"/>')
        if video:
            out.append(f'''    <video:video>
      <video:thumbnail_loc>{BASE}video/poster.jpg</video:thumbnail_loc>
      <video:title>منهج حياة: جولة في ميزات التطبيق</video:title>
      <video:description>جولة مدتها دقيقتان في ميزات تطبيق منهج حياة: المصحف والتفسير والتلاوة ومواقيت الصلاة والأذكار والسبحة.</video:description>
      <video:content_loc>{BASE}video/manhaj-hayah-promo.mp4</video:content_loc>
      <video:duration>119</video:duration>
      <video:publication_date>2026-09-28</video:publication_date>
      <video:family_friendly>yes</video:family_friendly>
    </video:video>''')
        out.append('  </url>')
    out.append('</urlset>')
    open(os.path.join(ROOT, 'sitemap.xml'), 'w').write('\n'.join(out) + '\n')


