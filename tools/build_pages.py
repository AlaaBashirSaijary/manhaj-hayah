def plain(t):
    return html.unescape(re.sub(r'<[^>]+>', '', t)).strip()


def jsonld(page, url, lang, crumbs, faq):
    graph = [
        {'@type': 'WebPage', '@id': url + '#page', 'url': url, 'name': plain(page['title']), 'description': page['desc'],
         'inLanguage': lang, 'isPartOf': {'@id': BASE + '#site'}, 'about': {'@id': BASE + '#app'},
         'primaryImageOfPage': {'@type': 'ImageObject', 'url': OG}, 'datePublished': DATE, 'dateModified': DATE,
         'author': PERSON, 'breadcrumb': {'@id': url + '#crumbs'}},
        {'@type': 'BreadcrumbList', '@id': url + '#crumbs', 'itemListElement': [
            {'@type': 'ListItem', 'position': i + 1, 'name': n, 'item': u} for i, (n, u) in enumerate(crumbs)]},
    ]
    if faq:
        graph.append({'@type': 'FAQPage', 'mainEntity': [
            {'@type': 'Question', 'name': q, 'acceptedAnswer': {'@type': 'Answer', 'text': plain(a)}} for q, a in faq]})
    return json.dumps({'@context': 'https://schema.org', '@graph': graph}, ensure_ascii=False, indent=1)


