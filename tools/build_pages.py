def render_blocks(blocks):
    out = []
    for b in blocks:
        kind = b[0]
        if kind == 'p':
            out.append(f'<p>{b[1]}</p>')
        elif kind == 'h3':
            out.append(f'<h3>{b[1]}</h3>')
        elif kind == 'ul':
            out.append('<ul class="points">' + ''.join(f'<li><span>{i}</span></li>' for i in b[1]) + '</ul>')
        elif kind == 'ol':
            out.append('<ol class="steps">' + ''.join(f'<li>{i}</li>' for i in b[1]) + '</ol>')
        elif kind == 'shots':
            wide = len(b) > 2 and b[2] == 'wide'
            figs = []
            for img, cap, alt in b[1]:
                w, h = (1080, 630) if img == 'share-card' else (540, 1170)
                figs.append(f'<figure><img src="../{app_img(img)}" alt="{esc(alt)}" width="{w}" height="{h}" loading="lazy">'
                            f'<figcaption>{esc(cap)}</figcaption></figure>')
            note = f'<p class="note">{esc(b[3])}</p>' if len(b) > 3 else ''
            out.append(f'<div class="shots{" wide" if wide else ""}">' + ''.join(figs) + '</div>' + note)
        elif kind == 'verify':
            out.append('<details class="verify" hidden><summary>بصمة الملف الحالي</summary>'
                       '<p>بصمة الملف <bdi class="sha-name"></bdi> (SHA-256):</p><p><code class="sha"></code></p></details>')
    return '\n'.join(out)


